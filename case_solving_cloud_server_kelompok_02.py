from itertools import combinations

import matplotlib
matplotlib.use("Agg")  # agar bisa jalan tanpa GUI
import matplotlib.pyplot as plt
import numpy as np
from scipy.optimize import linprog

# ----------------------------------------------------------------------
# 1. DATA MASALAH
# ----------------------------------------------------------------------
BIAYA = np.array([8000, 12000])          # Rp/jam : [Standar, Performa Tinggi]

# Kendala dalam bentuk  a1*x1 + a2*x2 >= b
A = np.array([[20, 10],                  # instruksi pemrosesan data per jam
              [10, 30]])                 # permintaan akses basis data per jam
B = np.array([100, 90])                  # kebutuhan minimal

NAMA_KENDALA = ["Pemrosesan data (>= 100)", "Akses basis data (>= 90)"]


def biaya(x1, x2, c=BIAYA):
    """Fungsi tujuan Z = c1*x1 + c2*x2."""
    return c[0] * x1 + c[1] * x2


def layak(x1, x2, tol=1e-9):
    """Cek apakah titik (x1, x2) memenuhi semua kendala."""
    return (x1 >= -tol and x2 >= -tol
            and np.all(A @ np.array([x1, x2]) >= B - tol))


# ----------------------------------------------------------------------
# 2. METODE TITIK SUDUT
# ----------------------------------------------------------------------
def cari_titik_sudut():
    """
    Semua kendala (termasuk x1>=0 dan x2>=0) ditulis sebagai garis batas.
    Titik sudut = perpotongan dua garis yang juga memenuhi semua kendala.
    """
    garis = [(A[0], B[0]), (A[1], B[1]),
             (np.array([1, 0]), 0),      # x1 = 0
             (np.array([0, 1]), 0)]      # x2 = 0
    titik = []
    for (a_i, b_i), (a_j, b_j) in combinations(garis, 2):
        M = np.array([a_i, a_j], dtype=float)
        if abs(np.linalg.det(M)) < 1e-12:  # garis sejajar
            continue
        x1, x2 = np.linalg.solve(M, np.array([b_i, b_j], dtype=float))
        if layak(x1, x2):
            titik.append((round(float(x1), 6), round(float(x2), 6)))
    return sorted(set(titik))

# ----------------------------------------------------------------------
# 3. VISUALISASI METODE GRAFIK
# ----------------------------------------------------------------------
def gambar_grafik(titik, optimum, nama_file="grafik_soal2.png"):
    x1 = np.linspace(0, 14, 400)
    k1 = (B[0] - A[0, 0] * x1) / A[0, 1]   # 20x1 + 10x2 = 100
    k2 = (B[1] - A[1, 0] * x1) / A[1, 1]   # 10x1 + 30x2 =  90

    fig, ax = plt.subplots(figsize=(8, 6.2), dpi=150)

    # Daerah layak = di atas kedua garis (kendala >=)
    batas_bawah = np.maximum(np.maximum(k1, k2), 0)
    ax.fill_between(x1, batas_bawah, 14, color="#9ecae1", alpha=0.55,
                    label="Daerah layak")

    ax.plot(x1, k1, color="#d95f02", lw=2, label=r"$20x_1+10x_2=100$")
    ax.plot(x1, k2, color="#1b9e77", lw=2, label=r"$10x_1+30x_2=90$")

    # Garis isocost melewati titik optimum
    z_opt = biaya(*optimum)
    isocost = (z_opt - BIAYA[0] * x1) / BIAYA[1]
    ax.plot(x1, isocost, "k--", lw=1.4,
            label=f"Garis biaya Z = Rp{z_opt:,.0f}".replace(",", "."))

    # Titik sudut
    for (px, py) in titik:
        ax.plot(px, py, "o", color="black", ms=6, zorder=5)
        z = biaya(px, py)
        ax.annotate(f"({px:g}; {py:g})\nZ=Rp{z:,.0f}".replace(",", "."),
                    (px, py), textcoords="offset points",
                    xytext=(10, 8), fontsize=8)

    ax.plot(*optimum, "*", color="red", ms=16, zorder=6, label="Titik optimum")

    ax.set_xlim(0, 12)
    ax.set_ylim(0, 12)
    ax.set_xlabel(r"$x_1$ : jam Server Standar")
    ax.set_ylabel(r"$x_2$ : jam Server Performa Tinggi")
    ax.set_title("Metode Grafik - Minimisasi Biaya Sewa Cloud Server")
    ax.grid(alpha=0.3)
    ax.legend(loc="upper right", fontsize=8)
    fig.tight_layout()
    fig.savefig(nama_file)
    plt.close(fig)

# ----------------------------------------------------------------------
# 4. PROGRAM UTAMA
# ----------------------------------------------------------------------
def rupiah(v):
    return "Rp" + f"{v:,.0f}".replace(",", ".")


def main():
    print("=" * 62)
    print("SOAL 2 - OPTIMASI BIAYA SEWA CLOUD SERVER")
    print("=" * 62)

    # --- Metode titik sudut ---
    titik = cari_titik_sudut()
    print("\n[1] Metode Titik Sudut (daerah layak tak terbatas ke atas/kanan)")
    print(f"{'Titik (x1, x2)':<20}{'Z = 8000x1 + 12000x2':>26}")
    hasil = []
    for (px, py) in titik:
        z = biaya(px, py)
        hasil.append(((px, py), z))
        print(f"({px:g}, {py:g})".ljust(20) + rupiah(z).rjust(26))
    (opt_xy, opt_z) = min(hasil, key=lambda t: t[1])
    print(f"\n    -> Biaya minimum di titik {opt_xy} dengan Z = {rupiah(opt_z)}")

    # --- Verifikasi solver ---
    # linprog hanya menerima <=, sehingga kendala >= dikali -1
    res = linprog(c=BIAYA, A_ub=-A, b_ub=-B, bounds=[(0, None), (0, None)],
                  method="highs")
    print("\n[2] Verifikasi scipy.optimize.linprog (HiGHS)")
    print(f"    status      : {res.message}")
    print(f"    x1 (Standar): {res.x[0]:.4f} jam")
    print(f"    x2 (Tinggi) : {res.x[1]:.4f} jam")
    print(f"    Z minimum   : {rupiah(res.fun)}")

    # --- Pengecekan kendala ---
    x1, x2 = res.x
    print("\n[3] Pengecekan kendala pada solusi optimum")
    for nama, (a, b) in zip(NAMA_KENDALA, zip(A, B)):
        nilai = a @ res.x
        status = "AKTIF (terpenuhi tepat)" if abs(nilai - b) < 1e-6 else "tidak aktif"
        print(f"    {nama:<28}: {nilai:7.2f}  -> {status}")

    # Dual / shadow price (marginals dari HiGHS, dibalik tanda karena -A)
    dual = -res.ineqlin.marginals
    print("\n[4] Harga bayangan (shadow price)")
    print(f"    Tambah 1 instruksi data -> biaya naik {rupiah(dual[0])}")
    print(f"    Tambah 1 permintaan DB  -> biaya naik {rupiah(dual[1])}")

    # --- Analisis sensitivitas biaya Server Standar ---
    print("\n[5] Sensitivitas: perubahan harga Server Standar (c1)")
    print(f"{'c1 (Rp/jam)':>12}{'x1':>8}{'x2':>8}{'Z (Rp)':>14}")
    for c1 in [4000, 6000, 8000, 10000, 12000, 20000, 40000]:
        r = linprog([c1, BIAYA[1]], A_ub=-A, b_ub=-B,
                    bounds=[(0, None)] * 2, method="highs")
        print(f"{c1:>12,}{r.x[0]:>8.2f}{r.x[1]:>8.2f}{r.fun:>14,.0f}"
              .replace(",", "."))
    # --- Kasus jam sewa harus bilangan bulat (integer programming sederhana) ---
    print("\n[6] Jika jam sewa harus bilangan bulat (enumerasi 0..20 jam)")
    terbaik = None
    for i in range(0, 21):
        for j in range(0, 21):
            if layak(i, j):
                z = biaya(i, j)
                if terbaik is None or z < terbaik[0]:
                    terbaik = (z, i, j)
    z_int, i_opt, j_opt = terbaik
    print(f"    x1 = {i_opt} jam, x2 = {j_opt} jam, Z = {rupiah(z_int)}")
    print(f"    Selisih terhadap solusi kontinu: {rupiah(z_int - res.fun)} "
          f"({(z_int - res.fun) / res.fun * 100:.2f}%)")

    # --- Konversi jam desimal ke jam:menit ---
    def jam_menit(h):
        return f"{int(h)} jam {round((h - int(h)) * 60)} menit"
    print(f"\n[7] Konversi: Standar = {jam_menit(x1)}, "
          f"Performa Tinggi = {jam_menit(x2)}")

    # --- Grafik ---
    gambar_grafik(titik, tuple(res.x))
    print("\nGrafik disimpan ke grafik_soal2.png")

    # --- Kesimpulan ---
    print("\n" + "=" * 62)
    print("KESIMPULAN")
    print(f"  Server Standar          : {x1:.1f} jam")
    print(f"  Server Performa Tinggi  : {x2:.1f} jam")
    print(f"  Total biaya minimum     : {rupiah(res.fun)}")
    print("=" * 62)


if __name__ == "__main__":
    main()